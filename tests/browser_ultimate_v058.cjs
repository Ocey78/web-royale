'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),{spawn}=require('node:child_process');
let chromium;try{({chromium}=require('playwright'));}catch{({chromium}=require('playwright'));}
const root=path.resolve(__dirname,'..'),out=path.join(root,'docs/qa/v058/ultimate'),report={errors:[],checks:[],screenshots:[]};
let server,browser;
async function main(){
 fs.mkdirSync(out,{recursive:true});
 server=spawn(process.execPath,['tools/serve.cjs','8098'],{cwd:root,stdio:['ignore','pipe','pipe'],windowsHide:true});
 await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);server.once('exit',code=>reject(Error('Preview exited '+code)));});
 browser=await chromium.launch({headless:true,...(process.env.BROWSER_EXECUTABLE?{executablePath:process.env.BROWSER_EXECUTABLE}:{})});
 const page=await browser.newPage({viewport:{width:1000,height:1080},serviceWorkers:'block'});
 page.on('pageerror',e=>report.errors.push(e.message));
 await page.goto('http://127.0.0.1:8098');
 await page.waitForFunction(()=>window.RoyaleDemo&&document.querySelector('#loading.hidden'),null,{timeout:240000});
 assert.equal(await page.evaluate(()=>RoyaleBundle.version),'0.58.0');
 const capture=async name=>{await page.locator('#viewport').screenshot({path:path.join(out,name+'.png')});report.screenshots.push(name+'.png');};
 await page.evaluate(()=>RoyaleDemo.show('events'));
 await page.locator('[data-action="special-deck-builder"][data-mode="UltimateClash"]').click();
 assert.equal(await page.locator('#modeDeckTitle').textContent(),'Ultimate Clash');
 assert.equal(await page.locator('#modeDeckCollection [data-action="special-deck-pick"]').count(),20);
 assert.equal(await page.locator('#modeDeckGrid .card-tile').count(),8);
 await page.waitForFunction(()=>[...document.querySelectorAll('#modeDeckCollection img')].every(i=>i.complete&&i.naturalWidth>0));
 report.checks.push('20 custom portraits loaded in independent eight-card deck builder');
 await capture('ultimate-deck');
 const normal=await page.evaluate(()=>JSON.stringify(RoyaleDemo.profile.decks));
 await page.locator('[data-action="special-deck-add"]').click();
 await page.locator('#modeDeckName').fill('Ultimate browser proof');await page.locator('#modeDeckName').press('Enter');
 await page.locator('#modeDeckCollection [data-id="ultimate-code-red"]').click();
 assert.equal(await page.evaluate(()=>JSON.stringify(RoyaleDemo.profile.decks)),normal);
 await page.reload();await page.waitForFunction(()=>window.RoyaleDemo&&document.querySelector('#loading.hidden'),null,{timeout:240000});
 const saved=await page.evaluate(()=>RoyaleDeckManager.modeState(RoyaleDemo.profile,'UltimateClash'));
 assert.equal(saved.names[saved.active],'Ultimate browser proof');assert.ok(saved.deck.includes('ultimate-code-red'));
 report.checks.push('custom deck edit and name survive reload without modifying ranked decks');
 await page.evaluate(()=>{RoyaleDemo.show('events');});
 await page.locator('[data-action="special-deck-builder"][data-mode="Default"]').click();
 assert.equal(await page.locator('#modeDeckCollection [data-id^="ultimate-"]').count(),0);
 await page.evaluate(()=>{RoyaleDemo.show('cards');RoyaleDemo.cardSection('collection');});
 assert.equal(await page.locator('#collection [data-id^="ultimate-"]').count(),0);
 report.checks.push('ordinary builders and collection exclude Ultimate cards');
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>RoyaleDemo.show('events'));await page.locator('[data-action="special-deck-builder"][data-mode="UltimateClash"]').click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2),false);await capture('ultimate-phone-deck');
 await page.setViewportSize({width:1000,height:1080});
 const play=await page.evaluate(async()=>{const ok=await RoyaleDemo.startBattle('UltimateClash',true,{seed:58071});if(!ok)return{ok,modal:RoyaleDemo.modal};const b=RoyaleDemo.battle;b.ai=false;b.elixir[0]=20;RoyaleDemo.refreshHand(true);return{ok,mode:b.mode,max:b.maxElixir,remaining:b.secondsLeft,deck:b.initialDecks[0]};});
 assert.equal(play.ok,true,JSON.stringify(play));assert.equal(play.mode,'UltimateClash');assert.equal(play.max,20);assert.ok(play.remaining>=237&&play.remaining<=240);
 assert.equal(await page.locator('.elixir-max').textContent(),'Max 20');
 await page.waitForTimeout(1200);await capture('ultimate-battle');
 report.checks.push('actual battle starts with 4-minute clock, custom deck and 20-elixir HUD');
 report.art=await page.evaluate(()=>Object.fromEntries(RoyaleCore.cardsForMode('UltimateClash').map(c=>[c.id,{cost:c.cost,description:c.description,art:!!RoyaleBundle.art[c.id]}])));
 assert.equal(Object.keys(report.art).length,20);assert.ok(Object.values(report.art).every(c=>c.art&&c.description.length>25));
 assert.deepEqual(report.errors,[]);report.passed=true;
}
main().catch(error=>{report.failure=error.stack;console.error(error);process.exitCode=1;}).finally(async()=>{fs.mkdirSync(out,{recursive:true});fs.writeFileSync(path.join(out,'report.json'),JSON.stringify(report,null,2));await browser?.close();server?.kill();console.log(JSON.stringify({passed:report.passed,checks:report.checks,errors:report.errors}));});
